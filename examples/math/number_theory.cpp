// 【使うもの】math/number_theory.hpp
// 【例題】整数 A, B と N が与えられる。次の 3 つを出力せよ。
//        ・A ÷ B の切り捨てと切り上げ（負の数もありうる）
//        ・√N の切り捨て
//        ・3^N を 1000000007 で割ったあまり
// 【入力例】
// -7 2
// 999999999999999999
// 【出力例】
// -4 -3
// 999999999
// 748778899

int main() {
    long long a, b, n;
    cin >> a >> b >> n;

    // C++ の a / b は 0 の方向に丸める（-7 / 2 = -3）ので、切り捨てには floor_div を使う
    cout << floor_div(a, b) << " " << ceil_div(a, b) << "\n";

    // (long long)sqrt(n) だと誤差で 1000000000 になってしまう
    cout << isqrt(n) << "\n";

    cout << pow_mod(3, n, 1000000007) << "\n";
}
