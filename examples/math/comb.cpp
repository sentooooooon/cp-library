// 【使うもの】math/comb.hpp
// 【例題】H 行 W 列のマス目の左上から右下まで、右か下に 1 マスずつ進んで行く。
//        行き方は何通りあるか。998244353 で割ったあまりを出力せよ。
// 【入力例】
// 3 4
// 【出力例】
// 10

int main() {
    int h, w;
    cin >> h >> w;

    Comb comb(h + w);  // 使う n の最大値以上を渡す
    // 全部で (h-1) + (w-1) 回進み、そのうちどの h-1 回を「下」にするか
    cout << comb.C(h + w - 2, h - 1) << "\n";
}
